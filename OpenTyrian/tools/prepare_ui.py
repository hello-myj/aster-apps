#!/usr/bin/env python3
"""Generate small bitmap font subset and instrument copies of upstream renderers."""
import hashlib,json,pathlib,re,urllib.request
from PIL import Image,ImageDraw,ImageFont
ROOT=pathlib.Path(__file__).resolve().parents[1]
FONT=ROOT/'artifacts/deps/NotoSansCJKsc-Regular.otf'
SHA='2c76254f6fc379fddfce0a7e84fb5385bb135d3e399294f6eeb6680d0365b74b'
if not FONT.exists():
    op=urllib.request.build_opener(urllib.request.ProxyHandler({}))
    FONT.parent.mkdir(parents=True,exist_ok=True)
    FONT.write_bytes(op.open('https://raw.githubusercontent.com/notofonts/noto-cjk/Sans2.004/Sans/OTF/SimplifiedChinese/NotoSansCJKsc-Regular.otf',timeout=120).read())
if hashlib.sha256(FONT.read_bytes()).hexdigest()!=SHA:raise RuntimeError('Font checksum mismatch')
mapping=json.loads((ROOT/'assets/zh-cn.json').read_text(encoding='utf-8'))
extra='射击确认暂停返回左翼右翼移动开始游戏自动演示'
chars=sorted(set(''.join(mapping.values())+extra),key=ord)
lines=['/* Noto Sans CJK SC 2.004 derived bitmap subset: SIL Open Font License 1.1.',
       ' * See vendor/licenses/Noto-OFL.txt. Generated by tools/prepare_ui.py. */',
       'static const unsigned short zh_codes[]={'+','.join(str(ord(c)) for c in chars)+'};',
       'static const unsigned char zh_sizes[]={16,12,10};',
       'static const unsigned short zh_bits[3]['+str(len(chars))+'][16]={']
for size in (16,12,10):
    font=ImageFont.truetype(str(FONT),size)
    lines.append('{')
    for ch in chars:
        im=Image.new('L',(16,16));d=ImageDraw.Draw(im);bbox=font.getbbox(ch)
        d.text((0,-bbox[1]),ch,font=font,fill=255)
        rows=[sum((1<<x) for x in range(size) if im.getpixel((x,y))>=100) for y in range(size)]
        lines.append('{'+','.join(str(x) for x in rows)+'},')
    lines.append('},')
lines.append('};')
lines.append('static const struct {const char *en,*zh;} zh_dictionary[]={')
for en,zh in mapping.items():
    key=''.join(c.lower() for c in en if c not in '~ \t\r\n')
    lines.append('{'+json.dumps(key)+','+json.dumps(zh,ensure_ascii=False)+'},')
lines.append('};')
(ROOT/'port/include/zh_data.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
# Preserve original notices, keep untouched upstream source for easy rebasing.
for filename in ('font.c','fonthand.c'):
    source=(ROOT/'vendor/upstream/src'/filename).read_text(encoding='utf-8')
    source='#include "localization.h"\n'+source
    if filename=='font.c':
        injections={
          'drawFontHv':'if(tyrian_zh_draw(surface,x,y,text,font,hue,value,0))return;',
          'drawFontHvBlend':'if(tyrian_zh_draw(surface,x,y,text,font,hue,value,0))return;',
          'drawFontDark':'if(tyrian_zh_draw(surface,x,y,text,font,0,0,1))return;'}
    else:
        injections={
          'JE_dString':'if(tyrian_zh_draw(screen,x+1,y+1,s,font,0,0,1)){tyrian_zh_draw(screen,x,y,s,font,15,-3,0);return;}',
          'JE_textWidth':'int zw=tyrian_zh_width(s,font);if(zw>=0)return zw;',
          'JE_outText':'if(tyrian_zh_draw(screen,x,y,s,2,colorbank,brightness,0))return;',
          'JE_outTextModify':'if(tyrian_zh_draw(screen,x,y,s,font,filter,brightness,0))return;',
          'JE_outTextAdjust':'if(tyrian_zh_draw(screen,x,y,s,font,filter,brightness,0))return;',
          'JE_outTextAndDarken':'if(tyrian_zh_draw(screen,x,y,s,font,colorbank,brightness,0))return;'}
    for name,code in injections.items():
        source,n=re.subn(r'((?:void|int) '+name+r'\([^\n]+\)\s*\{)',lambda m:m[1]+'\n '+code,source)
        if n!=1:raise RuntimeError('Renderer signature changed: '+name)
    (ROOT/'port'/filename).write_text(source,encoding='utf-8')
print('UI subset:',len(chars),'glyphs;',len(mapping),'translations')
