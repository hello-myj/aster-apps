#!/usr/bin/env python3
"""Original Pixel Wheels audio -> bounded PCM16 effects and quieter full BGM."""
from pathlib import Path
import wave,struct,math,json,subprocess,shutil,os,hashlib
P=Path(__file__).resolve().parents[1];A=P/'vendor/upstream/android/assets';O=P/'sdcard/aster/apps/aster.pixelwheels/data/resources';O.mkdir(parents=True,exist_ok=True)
# Two adjacent engine layers, one road loop and one priority cue fit four handles.
effects=[('loop_1_0.wav','engine0.wav',16000,None,23000),('loop_2_0.wav','engine1.wav',16000,None,23000),('loop_3_0.wav','engine2.wav',16000,None,23000),('loop_4_0.wav','engine3.wav',16000,None,23000),('loop_5_0.wav','engine4.wav',16000,None,23000),('drifting.wav','skid.wav',8000,None,22000),('countdown1.wav','countdown1.wav',16000,None,19000),('countdown2.wav','countdown2.wav',16000,None,19000),('impact.wav','impact.wav',16000,None,20000),('bonus.wav','pickup.wav',16000,None,20000),('turbo.wav','turbo.wav',16000,None,20000),('splash.wav','splash.wav',8000,3.8,20000),('points-increase.wav','lap.wav',16000,None,19000),('points-increase.wav','finish.wav',16000,None,20000)]
metadata=[]
for source,name,rate,maxsecs,target in effects:
    with wave.open(str(A/'sounds'/source),'rb') as r:
        source_rate=r.getframerate();channels=r.getnchannels();assert r.getsampwidth()==2
        raw=r.readframes(r.getnframes());v=struct.unpack('<%dh'%(len(raw)//2),raw)
    mono=[sum(v[i:i+channels])/channels for i in range(0,len(v),channels)]
    if maxsecs is not None:mono=mono[:round(source_rate*maxsecs)]
    count=round(len(mono)*rate/source_rate)
    output=[]
    for j in range(count):
        pos=j*source_rate/rate;i=min(int(pos),len(mono)-1);f=pos-i
        output.append(mono[i]*(1-f)+mono[min(i+1,len(mono)-1)]*f)
    peak=max(max(abs(x) for x in output),1);gain=target/peak
    out=[round(max(-32768,min(32767,x*gain))) for x in output]
    if not name.startswith('engine') and name!='skid.wav':
        fade=min(round(rate*.008),len(out)//2)
        for i in range(fade):out[i]=round(out[i]*i/fade);out[-1-i]=round(out[-1-i]*i/fade)
    pcm=struct.pack('<%dh'%len(out),*out)
    if len(pcm)>65536:raise SystemExit('Effect over 64KiB: '+name)
    with wave.open(str(O/name),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(rate);w.writeframes(pcm)
    rms=math.sqrt(sum(x*x for x in out)/len(out))
    metadata.append(dict(file=name,source='sounds/'+source,rate=rate,frames=len(out),pcm_bytes=len(pcm),duration_ms=math.ceil(len(out)*1000/rate),peak=max(abs(x) for x in out),rms=round(rms,2)))
    print(name,rate,len(pcm),'bytes',round(rms,1),'RMS')
header=['/* Generated by prepare_audio.py, source assets CC BY-SA 4.0. */','#pragma once', 'static const AudioCueDef cue_defs[]={']
for name in ('countdown1.wav','countdown2.wav','impact.wav','pickup.wav','turbo.wav','splash.wav','lap.wav','finish.wav'):
    entry=next(m for m in metadata if m['file']==name);header.append('{"%s",%d},'%(name,entry['duration_ms']))
header+=['};'];(P/'src/audio_catalog.h').write_text('\n'.join(header)+'\n',encoding='utf8')
(O/'audio-catalog.json').write_text(json.dumps(metadata,indent=2),encoding='utf8')
ffmpeg=os.environ.get('FFMPEG') or shutil.which('ffmpeg')
for name in ('country','city','snow'):
    src=A/f'musics/championships/{name}.mp3';dest=O/f'{name}.mp3'
    params=['-hide_banner','-loglevel','error','-y','-i',str(src),'-vn','-map_metadata','-1','-af','volume=0.354813','-c:a','libmp3lame','-b:a','128k','-ar','44100','-ac','2',str(dest)]
    if ffmpeg:command=[ffmpeg]+params
    elif os.name=='nt' and shutil.which('wsl'):
        def linux(path):
            s=str(path).replace('\\','/');return '/mnt/'+s[0].lower()+s[2:]
        params[params.index('-i')+1]=linux(src);params[-1]=linux(dest);command=['wsl','-d','Ubuntu-22.04','--exec','ffmpeg']+params
    else:raise SystemExit('Install ffmpeg or set FFMPEG before preparing music')
    subprocess.run(command,check=True)
    if dest.stat().st_size>=4*1024*1024:raise SystemExit('Music over device file limit')
print('BGM full duration, 128kbps, -9dB; PCM effects prepared')
